"""Runs the echo canceller over generated scenes and writes what it heard, so a person can check it without speakers.

    python -m voice.live.tests.echo_bench [--out DIR]

Each scene writes the microphone as it arrived, the microphone as the client would send it, and the reply that was
playing. `summary.json` holds the endpointer's starts, the canceller's counts and the measured levels. The exit
code is 1 if an expectation fails, so this doubles as a smoke test. All audio is generated by
`voice/live/tests/synthetic.py`; no microphone is opened and no real recording is read.
"""

import argparse
import json
import os
import sys
import wave
from datetime import datetime
from pathlib import Path

import numpy as np

from voice.live.aec import EchoCanceller, RATE, frame_dbfs
from voice.live.tests.synthetic import make_scene, run_scene

VOICE_HOME = Path(os.environ.get("VOICE_HOME", Path.home() / "voice"))


def write_wav(path, samples, rate=RATE):
    mono = np.clip(np.rint(np.asarray(samples) * 32768.0), -32768, 32767).astype("<i2")
    with wave.open(str(path), "wb") as out:
        out.setnchannels(1)
        out.setsampwidth(2)
        out.setframerate(rate)
        out.writeframes(mono.tobytes())


SCENES = (
    ("echo_only_loud", dict(echo_dbfs=-20.0), "no start"),
    ("echo_only_reverberant", dict(echo_dbfs=-26.0, tail_ms=100.0, delay_ms=60.0), "no start"),
    ("interruption", dict(echo_dbfs=-26.0, user=(2.0, 3.0, -18.0)), "start"),
    ("headphones", dict(echo_dbfs=None, user=(2.0, 3.0, -20.0)), "start"),
    ("playback_gap", dict(echo_dbfs=-26.0, reply_gaps=((1.0, 1.6), (3.0, 3.6))), "no start"),
)


def run(out_dir):
    out_dir.mkdir(parents=True, exist_ok=True)
    summary, failures = [], []
    for name, options, expected in SCENES:
        scene = make_scene(6.0, **options)
        result = run_scene(scene, EchoCanceller(), playback_rate=24_000)
        echo_span = slice(int(2.0 * RATE), int(5.5 * RATE))
        record = {
            "scene": name,
            "options": {key: (list(value) if isinstance(value, tuple) else value)
                        for key, value in options.items()},
            "expected": expected,
            "starts": list(result.starts),
            "echo_db": round(frame_dbfs(scene.microphone[echo_span]), 1),
            "sent_db": round(frame_dbfs(result.cleaned[echo_span]), 1),
            "stats": result.stats,
        }
        ok = (not result.starts) if expected == "no start" else bool(result.starts)
        record["ok"] = ok
        if not ok:
            failures.append(name)
        write_wav(out_dir / f"{name}-microphone-raw.wav", scene.microphone)
        write_wav(out_dir / f"{name}-microphone-sent.wav", result.cleaned)
        write_wav(out_dir / f"{name}-reply-played.wav", scene.reference)
        write_wav(out_dir / f"{name}-conversation-raw.wav",
                  scene.reference[:len(result.cleaned)] + scene.microphone[:len(result.cleaned)])
        write_wav(out_dir / f"{name}-conversation-sent.wav", scene.reference[:len(result.cleaned)] + result.cleaned)
        summary.append(record)
        print(f"{name:22s} starts={str(list(result.starts)):12s} echo={record['echo_db']:6.1f} dB "
              f"sent={record['sent_db']:6.1f} dB erle={result.stats['erle_db']} "
              f"suppressed={result.stats['suppressed_frames']}/{result.stats['playing_frames']} "
              f"{'ok' if ok else 'FAILED'}")
    (out_dir / "summary.json").write_text(json.dumps(summary, indent=1) + "\n", encoding="utf-8")
    print(f"wrote {len(SCENES)} scenes to {out_dir}")
    return failures


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path,
                        default=VOICE_HOME / "evidence" / "echo" / datetime.now().strftime("%Y%m%d-%H%M%S"))
    args = parser.parse_args()
    failures = run(args.out)
    if failures:
        print(f"failed scenes: {', '.join(failures)}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
